function renderAnalytics() {
    const stats = document.getElementById("preStockStats");
    const canvas = document.getElementById("preStockProfile");
    if (!stats || !canvas || !currentMatrix.length) return;
    const rows = currentMatrix.length, cols = currentMatrix[0].length;
    const rowCounts = currentMatrix.map(row => row.reduce((a, b) => a + b, 0));
    const total = rowCounts.reduce((a, b) => a + b, 0);
    const density = total / (rows * cols) * 100;
    const min = Math.min(...rowCounts), max = Math.max(...rowCounts);
    const avg = total / rows;
    const columnCounts = Array.from({length:cols}, (_, c) =>
        currentMatrix.reduce((sum, row) => sum + row[c], 0));
    const balanced = Math.max(...columnCounts) - Math.min(...columnCounts);
    stats.innerHTML = [
      ["Picks", rows], ["Ends", cols], ["Total UP", total],
      ["UP Density", `${density.toFixed(1)}%`], ["Avg UP / Pick", avg.toFixed(1)],
      ["Pick range", `${min}–${max}`], ["End imbalance", balanced]
    ].map(([label,value]) => `<div class="ps-stat"><span class="ps-muted">${label}</span><b>${value}</b></div>`).join("");
    const ctx = canvas.getContext("2d");
    if (!ctx) return;
    const w = canvas.width, h = canvas.height, pad = 34;
    ctx.clearRect(0,0,w,h);
    ctx.strokeStyle = "#334155"; ctx.lineWidth = 1;
    for (let i=0;i<=4;i++) {
      const y = pad + (h-pad*1.5)*i/4;
      ctx.beginPath(); ctx.moveTo(pad,y); ctx.lineTo(w-10,y); ctx.stroke();
    }
    const chartW = w-pad-12, chartH = h-pad*1.5, step = chartW/rows;
    const barW = Math.max(2, step*0.68);
    rowCounts.forEach((value,i) => {
      const bh = max ? value/max*chartH : 0;
      ctx.fillStyle = "#38bdf8";
      ctx.fillRect(pad+i*step+(step-barW)/2, pad+chartH-bh, barW, bh);
    });
    ctx.fillStyle="#cbd5e1"; ctx.font="12px sans-serif";
    ctx.fillText("UP",6,16); ctx.fillText("Pick number →",w-105,h-7);
    const health = document.getElementById("preStockHealth");
    const emptyRows = rowCounts.filter(n=>n===0).length;
    const fullRows = rowCounts.filter(n=>n===cols).length;
    health.textContent = `Design check: ${emptyRows ? emptyRows+" empty pick(s). " : "No empty picks. "}${fullRows ? fullRows+" fully-up pick(s). " : ""}End-wise UP count ranges from ${Math.min(...columnCounts)} to ${Math.max(...columnCounts)}.`;
}
