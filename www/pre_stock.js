const PRE_STOCK_BITMAP_CLOUD_KEY = "pre_stock_bitmap_designs";
function getSavedPreStockDesigns() {
    if (typeof window.firebaseLoad !== "function") return {};
    const saved = window.firebaseLoad(PRE_STOCK_BITMAP_CLOUD_KEY, {});
    return saved && typeof saved === "object" && !Array.isArray(saved) ? saved : {};
}
function mergePreStockDesigns(saved) {
    if (!saved || typeof saved !== "object" || Array.isArray(saved)) return;
    Object.entries(saved).forEach(([key, design]) => {
        if (!key || !design || typeof design !== "object" || !Array.isArray(design.matrix)) return;
        if (!design.matrix.length || !design.matrix.every(row => Array.isArray(row))) return;
        // Never allow cloud/user data to replace the built-in designs.
        if (Object.prototype.hasOwnProperty.call(preDefinedDesigns, key) && !preDefinedDesigns[key]?.__userSaved) return;
        preDefinedDesigns[key] = {
            name: String(design.name || key),
            formula: String(design.formula || `(1-${design.matrix.length})`),
            matrix: normalizeMatrix(design.matrix),
            __userSaved: true
        };
    });
}

