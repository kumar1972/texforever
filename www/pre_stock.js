    panel.setAttribute("role", "listbox");
    const search = document.createElement("input");
    search.type = "search"; search.className = "ps-search";
    search.placeholder = "Search weave designs…";
    search.setAttribute("aria-label", "Search weave designs");
    const list = document.createElement("div"); list.className = "ps-list";
    panel.append(search, list);
    document.body.appendChild(panel);

    // Insert the visual control exactly where the original select was located.
    weaveSelect.insertAdjacentElement("beforebegin", root);
    weaveSelect.classList.add("pre-stock-native-hidden");
    weaveSelect.setAttribute("aria-hidden", "true");
