const MAX_ROWS = 64;
const MAX_COLS = 32;

function cloneMatrix(matrix) {
    return matrix.map(row => row.slice());
}
function validMatrix(matrix) {
    return Array.isArray(matrix) && matrix.length >= 2 &&
        matrix.length <= MAX_ROWS && Array.isArray(matrix[0]) &&
        matrix[0].length >= 2 && matrix[0].length <= MAX_COLS &&
        matrix.every(row => Array.isArray(row) && row.length === matrix[0].length &&
            row.every(value => value === 0 || value === 1));
}
function normalizeMatrix(matrix) {
    if (!Array.isArray(matrix) || !matrix.length) return [[0, 1], [1, 0]];
    const width = Math.max(2, Math.min(MAX_COLS,
        ...matrix.map(row => Array.isArray(row) ? row.length : 0)));
    const rows = matrix.slice(0, MAX_ROWS).map(row =>
        Array.from({ length: width }, (_, i) => Number(row?.[i]) === 1 ? 1 : 0)
    );
    while (rows.length < 2) rows.push(new Array(width).fill(0));
    return rows;
}
function rememberState() {
    undoStack.push({
        matrix: cloneMatrix(currentMatrix),
        formula: currentFormula,
        name: currentDesignName
    });
    if (undoStack.length > 80) undoStack.shift();
    redoStack = [];
}
function syncFormula() {
    currentFormula = `(1-${currentMatrix.length})`;
    if (formulaInput) formulaInput.value = currentFormula;
}
